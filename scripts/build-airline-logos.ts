/**
 * Bundles airline logos so the app can show them offline.
 * Run: npm run data:logos   (dev only, needs network; downloads are cached in scripts/.cache/logos)
 *
 * Sources (by ICAO code, first hit wins):
 *   1. github.com/Jxck-S/airline-logos  flightaware_logos/<ICAO>.png
 *   2. github.com/sexym0nk3y/airline-logos  logos/<ICAO>.png
 * Logos are trademarks of their airlines and are used only to identify the airline.
 *
 * Outputs: assets/airline-logos/<IATA>.png (96×96, transparent) and src/data/airlineLogos.ts.
 */
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve(__dirname, '..');
const cacheDir = path.join(root, 'scripts', '.cache', 'logos');
const outDir = path.join(root, 'assets', 'airline-logos');
const SIZE = 96;

const SOURCES = [
  (icao: string) =>
    `https://raw.githubusercontent.com/Jxck-S/airline-logos/main/flightaware_logos/${icao}.png`,
  (icao: string) =>
    `https://raw.githubusercontent.com/sexym0nk3y/airline-logos/main/logos/${icao}.png`,
];

async function fetchCached(icao: string): Promise<Buffer | null> {
  const file = path.join(cacheDir, `${icao}.png`);
  const miss = path.join(cacheDir, `${icao}.miss`);
  if (fs.existsSync(file)) return fs.readFileSync(file);
  if (fs.existsSync(miss)) return null;
  for (const src of SOURCES) {
    try {
      const res = await fetch(src(icao));
      if (!res.ok) continue;
      const buf = Buffer.from(await res.arrayBuffer());
      fs.writeFileSync(file, buf);
      return buf;
    } catch {
      // try the next source
    }
  }
  fs.writeFileSync(miss, '');
  return null;
}

async function main() {
  fs.mkdirSync(cacheDir, { recursive: true });
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  const airlines: { iata: string; icao: string }[] = JSON.parse(
    fs.readFileSync(path.join(root, 'assets', 'data', 'airlines.json'), 'utf8'),
  );
  const found: string[] = [];
  const queue = [...airlines];
  const worker = async () => {
    for (let a = queue.shift(); a; a = queue.shift()) {
      if (!a.icao || !/^[A-Z0-9]{2}$/.test(a.iata)) continue;
      const buf = await fetchCached(a.icao);
      if (!buf) continue;
      try {
        await sharp(buf)
          .trim({ threshold: 4 })
          .resize(SIZE, SIZE, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
          .png({ compressionLevel: 9, palette: true })
          .toFile(path.join(outDir, `${a.iata}.png`));
        found.push(a.iata);
      } catch {
        // unreadable image; skip
      }
    }
  };
  await Promise.all(Array.from({ length: 12 }, worker));
  found.sort();
  const lines = found.map((c) => `  '${c}': require('../../assets/airline-logos/${c}.png'),`);
  fs.writeFileSync(
    path.join(root, 'src', 'data', 'airlineLogos.ts'),
    `// Generated by scripts/build-airline-logos.ts — do not edit.\n` +
      `// Logos are trademarks of their respective airlines.\n` +
      `export const AIRLINE_LOGOS: Record<string, number> = {\n${lines.join('\n')}\n};\n`,
  );
  console.log(`Bundled ${found.length} of ${airlines.length} airline logos`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
